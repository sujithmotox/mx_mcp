// Regenerates db/init/02-seed.sql with deterministic sample data.
// Usage: node scripts/generate-seed.mjs > db/init/02-seed.sql
let s = 42;
const rnd = () => ((s = (s * 1103515245 + 12345) % 2 ** 31) / 2 ** 31);
const pick = (a) => a[Math.floor(rnd() * a.length)];
const pad = (n) => String(n).padStart(2, "0");
const dt = (d) => `${d.getUTCFullYear()}-${pad(d.getUTCMonth() + 1)}-${pad(d.getUTCDate())} ${pad(d.getUTCHours())}:${pad(d.getUTCMinutes())}:00`;
const q = (v) => `'${String(v).replace(/'/g, "''")}'`;

const first = ["Ava","Liam","Noah","Mia","Arjun","Priya","Sofia","Lucas","Yuki","Omar","Chen","Fatima","Elena","Mateo","Zara","Ravi","Hana","Leo","Ines","Kofi"];
const last = ["Patel","Garcia","Kim","Silva","Nguyen","Müller","Rossi","Khan","Okafor","Tanaka","Smith","Dubois","Haddad","Costa","Iyer"];
const countries = ["US","IN","GB","DE","BR","JP","FR","AE","NG","CA","AU","ES"];
const catalogue = {
  Helmets: [["Trail Helmet", 189], ["Carbon MX Helmet", 449], ["Youth Helmet", 129]],
  Goggles: [["Roll-off Goggles", 79], ["Tinted Goggles", 49], ["Anti-fog Lens", 19]],
  Apparel: [["Race Jersey", 59], ["Riding Pants", 139], ["Gloves", 35], ["Hoodie", 69]],
  Protection: [["Knee Braces", 299], ["Chest Protector", 159], ["Neck Brace", 349], ["Elbow Guards", 45]],
  Parts: [["Brake Pads", 39], ["Chain Kit", 129], ["Air Filter", 25], ["Handlebar", 99], ["Grips", 15], ["Sprocket", 55]],
  Boots: [["MX Boots", 399], ["Enduro Boots", 329], ["Boot Socks", 18]],
};

const out = ["-- Generated by scripts/generate-seed.mjs. Sample data only.", "SET NAMES utf8mb4;"];

const customers = [];
for (let i = 1; i <= 60; i++) {
  const f = pick(first), l = pick(last);
  const created = new Date(Date.UTC(2024, 0, 1) + rnd() * 600 * 86400e3);
  customers.push({ id: i, created });
  out.push(`INSERT INTO customers (id,name,email,country,created_at) VALUES (${i},${q(`${f} ${l}`)},${q(`${f}.${l}${i}@example.com`.toLowerCase())},${q(pick(countries))},${q(dt(created))});`);
}

const products = [];
let pid = 0;
for (const [cat, items] of Object.entries(catalogue))
  for (const [name, price] of items) {
    pid++;
    products.push({ id: pid, price });
    out.push(`INSERT INTO products (id,sku,name,category,price) VALUES (${pid},${q(`${cat.slice(0, 3).toUpperCase()}-${1000 + pid}`)},${q(name)},${q(cat)},${price.toFixed(2)});`);
  }

const statuses = ["paid","paid","shipped","shipped","shipped","pending","cancelled","refunded"];
let itemId = 0;
const end = Date.UTC(2026, 10, 10);
for (let o = 1; o <= 700; o++) {
  const c = pick(customers);
  const start = Math.max(c.created.getTime(), Date.UTC(2024, 6, 1));
  const created = new Date(start + rnd() * (end - start));
  const lines = [];
  const n = 1 + Math.floor(rnd() * 4);
  for (let k = 0; k < n; k++) {
    const p = pick(products);
    const qty = 1 + Math.floor(rnd() * 3);
    const unit = +(p.price * (rnd() < 0.2 ? 0.85 : 1)).toFixed(2);
    lines.push({ id: ++itemId, p: p.id, qty, unit });
  }
  const total = lines.reduce((a, l) => a + l.qty * l.unit, 0).toFixed(2);
  out.push(`INSERT INTO orders (id,customer_id,status,total,created_at) VALUES (${o},${c.id},${q(pick(statuses))},${total},${q(dt(created))});`);
  out.push(`INSERT INTO order_items (id,order_id,product_id,quantity,unit_price) VALUES ${lines.map((l) => `(${l.id},${o},${l.p},${l.qty},${l.unit.toFixed(2)})`).join(",")};`);
}
console.log(out.join("\n"));
